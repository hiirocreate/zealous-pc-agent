"""読み上げ用に、同じ表記で読み方が変わる言葉を、文の流れから読み分ける(画面の文字はそのまま)。
例: 「確認を行っている」→ おこなっている / 「東京へ行っている」→ いっている"""
import re

import config

# 「〜を行う」「〜(の)作業を行う」のように使われやすい言葉(この後の「行っ」は「おこなっ」)
_DO_NOUNS = ("調査|検査|処理|作業|手続き|実施|対応|説明|発表|会議|練習|工事|管理|運営|更新|設定|変更|検討|分析|操作|撮影|"
             "治療|手術|取引|試験|実験|開発|販売|確認|点検|修理|整備|改善|調整|準備|計算|集計|登録|申請|審査|評価|"
             "研究|議論|交渉|演奏|上演|講演|放送|配信|選挙|投票|募集|採用|指導|支援|活動|運動|行事|祭り|イベント|"
             "検証|翻訳|編集|保存|削除|移動|検索|予約|決済|支払い|送信|受信|通信|学習|訓練|作成|制作|製作")

_RULES = [
    # 「を行っ」「を行わ」など(〜をする意味)は「おこな」
    (re.compile(r"(?<=を)行(?=[っわい])"), "おこな"),
    # 「作業行っ」「確認も行っ」のように、するという意味の言葉の直後(間に助詞「も・は・が」が入ってもよい)
    (re.compile(rf"((?:{_DO_NOUNS})[もはが]?)行(?=[っわい])"), r"\1おこな"),
    # 「行う」「行い(ます)」「行わ(ない/れる)」「行え(る)」は、いつも「おこな」(「いく」は 行く・行き・行か・行け)
    (re.compile(r"(?<![流銀旅飛急])行(?=[うわえ]|い(?!く))"), "おこな"),
]


def fix(text):
    """読み上げ用の文に直す(読み方の辞書と、文の流れによる読み分け)。"""
    for rule in getattr(config, "READINGS", []) or []:  # 設定の「読み方の辞書」(表記=よみ)
        word, sep, yomi = str(rule).partition("=")
        if sep and word.strip() and yomi.strip():
            text = text.replace(word.strip(), yomi.strip())
    for pattern, repl in _RULES:
        text = pattern.sub(repl, text)
    return text
