_DAYS = {"今日": 0, "きょう": 0, "本日": 0, "明日": 1, "あした": 1, "あす": 1, "明後日": 2, "あさって": 2}


def describe(code):
    return next((name for codes, name in _CODES if code in codes), "不明")


def find_place(text):
    """文の中の地名 (名前, 緯度, 経度)。見つからなければ None。"""
    for name in sorted(PLACES, key=len, reverse=True):
        if name in text:
            return name, *PLACES[name]
    return None


def parse(text):
    """「明日の東京の天気」→ (場所の名前 または None, 何日後か)"""
    day = next((d for word, d in sorted(_DAYS.items(), key=lambda x: -len(x[0])) if word in text), 0)
    place = find_place(text)
    return (place[0] if place else None), day


def forecast(lat, lon, days=3):
    url = ("https://api.open-meteo.com/v1/forecast?" + urllib.parse.urlencode({
        "latitude": lat, "longitude": lon, "timezone": "Asia/Tokyo", "forecast_days": days,
        "daily": "weather_code,temperature_2m_max,temperature_2m_min,precipitation_probability_max"}))
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "Zealous"}), timeout=10) as r:
        return json.load(r)["daily"]


def report(place, day=0):
    """「明日の東京は晴れ時々くもり、最高22度・最低14度、降水確率10%の予報です。」"""
    name, lat, lon = place if isinstance(place, tuple) else (place, *PLACES[place])
    d = forecast(lat, lon, max(3, day + 1))
    i = min(day, len(d["time"]) - 1)
    when = {0: "今日", 1: "明日", 2: "明後日"}.get(day, d["time"][i])
    rain = d["precipitation_probability_max"][i]
    return (f"{when}の{name}は{describe(d['weather_code'][i])}、最高{round(d['temperature_2m_max'][i])}度・"
            f"最低{round(d['temperature_2m_min'][i])}度" + (f"、降水確率{rain}%" if rain is not None else "")
            + "の予報です。")


def is_weather(text):
    return bool(re.search(r"天気|気温|降水|雨降る|雨が降る|晴れる|傘いる|傘が要る|天気予報", text))
